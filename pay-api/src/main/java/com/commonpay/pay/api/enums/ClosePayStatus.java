package com.commonpay.pay.api.enums;

/**
 * 渠道关单的业务结果。
 * <p>只表达「渠道明确告诉你的三种答案」；调用本身失败（超时/网络/渠道不支持）用抛异常表达 ——
 * 那种情况下你【不知道】凭证还在不在，绝不能当成可关。
 */
public enum ClosePayStatus {

    /** 渠道已关闭，凭证失效，用户再也付不了 → 可以放心关本地 */
    CLOSED,

    /** 渠道已支付，关不掉 → 绝不能关本地，要等支付回调把它推进成已支付 */
    ALREADY_PAID,

    /** 渠道查无此单，凭证压根不存在 → 等同可关 */
    NOT_FOUND
}
